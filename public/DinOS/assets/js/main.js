document.addEventListener("DOMContentLoaded", () => {
  // Menú móvil
  const toggle = document.querySelector(".menu-toggle");
  const nav = document.querySelector(".nav");
  if (toggle && nav) {
    toggle.innerHTML = svg("menu");
    toggle.addEventListener("click", () => {
      const open = nav.classList.toggle("open");
      toggle.setAttribute("aria-expanded", open);
      toggle.innerHTML = svg(open ? "x" : "menu");
    });
  }

  // Cabecera más sólida al hacer scroll
  const header = document.querySelector(".header");
  const onScroll = () => header && header.classList.toggle("scrolled", scrollY > 10);
  addEventListener("scroll", onScroll, { passive: true }); onScroll();

  // Enlace activo según la página
  const page = location.pathname.split("/").pop() || "index.html";
  document.querySelectorAll(".nav > a[href]").forEach((a) => {
    if (a.getAttribute("href") === page) a.classList.add("active");
  });

  // Año en el footer
  document.querySelectorAll("[data-year]").forEach((el) => (el.textContent = new Date().getFullYear()));

  // Duplicar la franja de sectores para que el desplazamiento sea continuo
  document.querySelectorAll(".marquee__track").forEach((t) => { t.innerHTML += t.innerHTML; });

  // Aparición al hacer scroll
  const targets = document.querySelectorAll(
    ".section__head, .card, .feature-row, .plan, .step, .tl-item, .versus__col, .faq details, .cta, .table-wrap, .chat-window, .hero__grid > *, .stat, .page-hero .container"
  );
  targets.forEach((el) => el.classList.add("reveal"));
  // Pequeño escalonado entre hermanos
  targets.forEach((el) => {
    const sibs = [...el.parentElement.children].filter((c) => c.classList.contains("reveal"));
    const i = sibs.indexOf(el);
    if (i > 0) el.style.transitionDelay = Math.min(i, 6) * 80 + "ms";
  });
  if ("IntersectionObserver" in window) {
    const io = new IntersectionObserver((entries) => {
      entries.forEach((e) => { if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); } });
    }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });
    targets.forEach((el) => io.observe(el));
  } else {
    targets.forEach((el) => el.classList.add("in"));
  }

  // Contadores animados (data-count)
  document.querySelectorAll("[data-count]").forEach((el) => {
    const end = parseFloat(el.dataset.count), suf = el.dataset.suffix || "";
    const run = () => {
      const t0 = performance.now();
      const step = (t) => {
        const p = Math.min((t - t0) / 1400, 1), v = Math.round(end * (1 - Math.pow(1 - p, 3)));
        el.textContent = v + suf; if (p < 1) requestAnimationFrame(step);
      };
      requestAnimationFrame(step);
    };
    if ("IntersectionObserver" in window) {
      const o = new IntersectionObserver((en) => { if (en[0].isIntersecting) { run(); o.disconnect(); } });
      o.observe(el);
    } else el.textContent = end + suf;
  });

  // Formulario de contacto (sin envío real todavía: falta definir a dónde llegan los mensajes)
  const form = document.querySelector("#contact-form");
  if (form) {
    const plan = new URLSearchParams(location.search).get("plan");
    if (plan && form.plan) form.plan.value = plan;
    form.addEventListener("submit", (e) => {
      e.preventDefault();
      if (!form.checkValidity()) { form.reportValidity(); return; }
      form.querySelector(".form__ok").style.display = "block";
      form.reset();
    });
  }
});
